def build_digest_html(**ctx) -> str:
    return DIGEST_TMPL.render(**ctx)


def send_digest(subject: str, html: str, attachments: list[Path], to: str) -> bool:
    user, pw = env("GMAIL_USER"), env("GMAIL_APP_PASSWORD")
    if not (user and pw):
        log.info("GMAIL_USER/GMAIL_APP_PASSWORD not set - digest written to disk only")
        return False
    msg = EmailMessage()
    msg["From"], msg["To"], msg["Subject"], msg["Date"] = user, to, subject, formatdate(localtime=True)
    msg.set_content("HTML digest attached/inline. Open in an HTML mail client.")
    msg.add_alternative(html, subtype="html")
    for p in attachments[:20]:
        data = p.read_bytes()
        if p.suffix == ".pdf":
            msg.add_attachment(data, maintype="application", subtype="pdf", filename=p.name)
        elif p.suffix == ".docx":
            msg.add_attachment(data, maintype="application",
                               subtype="vnd.openxmlformats-officedocument.wordprocessingml.document", filename=p.name)
        else:
            msg.add_attachment(data, maintype="text", subtype="plain", filename=p.name)
    with smtplib.SMTP_SSL("smtp.gmail.com", 465, timeout=60) as s:
        s.login(user, pw)
        s.send_message(msg)
    return True


def create_gmail_draft(to: str, subject: str, body: str, attachments: list[Path]) -> bool:
    """IMAP APPEND into [Gmail]/Drafts. Shows up as a normal draft in Gmail for you to review and send."""
    user, pw = env("GMAIL_USER"), env("GMAIL_APP_PASSWORD")
    if not (user and pw):
        return False
    msg = EmailMessage()
    msg["From"], msg["Subject"], msg["Date"] = user, subject, formatdate(localtime=True)
    if to:
        msg["To"] = to
    msg.set_content(body)
    for p in attachments:
        data = p.read_bytes()
        sub = "pdf" if p.suffix == ".pdf" else "vnd.openxmlformats-officedocument.wordprocessingml.document"
        msg.add_attachment(data, maintype="application", subtype=sub, filename=p.name)
    try:
        M = imaplib.IMAP4_SSL("imap.gmail.com", 993)
        M.login(user, pw)
        M.append("[Gmail]/Drafts", "\\Draft", imaplib.Time2Internaldate(time.time()), msg.as_bytes())
        M.logout()
        return True
    except imaplib.IMAP4.error as e:
        log.warning("draft creation failed: %s", e)
        return False
